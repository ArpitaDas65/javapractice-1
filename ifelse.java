 public class ifelse {
    public static void main(String[]args) {

        //declare and initialize score
        int score=85;
        //conditional statement
        if(score>=90){
            System.out.println("excellent!");
        }
        else if(score>=70){
            System.out.println("good!");
        }
        else{
            System.out.println("needs improvement.");
        }
    }
    
}
