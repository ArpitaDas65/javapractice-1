public class forloopnwhileloop {
    public static void main(String[] args) {
        //for loop
        System.out.println("for loop:");
        for(int i=1;i<=5;i++){
            System.out.println("iteration"+i);
        }
        //while loop
        System.out.println("while loop");
        int j=1;
        while (j<=5) {
            System.out.println("iteration"+j);
            j++;
            
            
        }
    }
    
}
